// Filtro por Categorías
function filtrarCategoria(cat, elemento) {
    document.getElementById('input-buscar').value = '';
    document.querySelectorAll('.btn-cat, .dropdown-contenido .btn-cat').forEach(btn => btn.classList.remove('activo'));
    
    if (elemento) {
        elemento.classList.add('activo');
        const contenedorDropdown = elemento.closest('.dropdown-categoria');
        if (contenedorDropdown) {
            contenedorDropdown.querySelector('.btn-dropdown').classList.add('activo');
        }
    }

    const subcategoriasLubricantes = [
        'lubricantes', 'saborizados', 'cremas-anales', 
        'efecto-frio', 'efecto-calor', 'orgasmicos', 'efecto-retardante', 'aceites'
    ];

    let filtrados;
    if (cat === 'todos') {
        filtrados = productos;
    } else if (cat === 'lubricantes') {
        // Verifica si al menos UNA de las categorías del producto está en el grupo de lubricantes
        filtrados = productos.filter(p => 
            Array.isArray(p.categoria)
                ? p.categoria.some(c => subcategoriasLubricantes.includes(c))
                : subcategoriasLubricantes.includes(p.categoria)
        );
    } else {
        // Verifica si la categoría buscada está dentro del array de categorías del producto
        filtrados = productos.filter(p => 
            Array.isArray(p.categoria)
                ? p.categoria.includes(cat)
                : p.categoria === cat
        );
    }

    mostrarProductosEnPantalla(filtrados);
}
// Agregar al carrito
function agregarAlCarrito(id, colorElegido = null, cantidadSumar = 1) {
    const prod = productos.find(p => p.id === id);
    const colorFinal = colorElegido || (prod.colores ? prod.colores[0] : null);
    
    const existe = carrito.find(item => item.id === id && item.color === colorFinal);

    if (existe) {
        existe.cantidad += cantidadSumar;
    } else {
        carrito.push({ ...prod, cantidad: cantidadSumar, color: colorFinal });
    }

    actualizarCarritoUI();
}

// Cambiar cantidades en carrito lateral
function cambiarCantidad(id, color, cambio) {
    const item = carrito.find(p => p.id === id && p.color === color);
    if (!item) return;

    item.cantidad += cambio;

    if (item.cantidad <= 0) {
        carrito = carrito.filter(p => !(p.id === id && p.color === color));
    }

    actualizarCarritoUI();
}

// Actualizar Carrito UI
function actualizarCarritoUI() {
    const totalItems = carrito.reduce((acc, item) => acc + item.cantidad, 0);
    document.getElementById('cant-carrito').innerText = totalItems;

    const listaContenedor = document.getElementById('lista-carrito');
    listaContenedor.innerHTML = '';

    if (carrito.length === 0) {
        listaContenedor.innerHTML = '<p style="text-align: center; color: #888; margin-top: 20px;">El carrito está vacío.</p>';
        document.getElementById('monto-total').innerText = '$0';
        return;
    }

    let totalMonto = 0;

    carrito.forEach(item => {
        const subtotal = item.precio * item.cantidad;
        totalMonto += subtotal;

        const detalleColor = item.color ? ` <small style="color:#777;">(${item.color})</small>` : '';

        listaContenedor.innerHTML += `
            <div class="item-carrito">
                <div class="item-info">
                    <h4>${item.nombre}${detalleColor}</h4>
                    <p>$${subtotal.toLocaleString('es-AR')}</p>
                </div>
                <div class="item-controles">
                    <button class="btn-cantidad" onclick="cambiarCantidad(${item.id}, '${item.color}', -1)">-</button>
                    <span>${item.cantidad}</span>
                    <button class="btn-cantidad" onclick="cambiarCantidad(${item.id}, '${item.color}', 1)">+</button>
                </div>
            </div>
        `;
    });

    document.getElementById('monto-total').innerText = `$${totalMonto.toLocaleString('es-AR')}`;
}

