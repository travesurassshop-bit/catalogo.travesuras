// Renderizar productos en pantalla
function mostrarProductosEnPantalla(lista) {
    const contenedor = document.getElementById('grid-productos');
    contenedor.innerHTML = '';

    if (lista.length === 0) {
        contenedor.innerHTML = '<p style="grid-column: 1/-1; text-align: center; padding: 2rem; color: #888;">No se encontraron productos coincidentes.</p>';
        return;
    }

    lista.forEach(prod => {
        const imgPrincipal = prod.imagenes ? prod.imagenes[0] : prod.imagen;
        contenedor.innerHTML += `
            <div class="tarjeta-producto">
                <img src="${imgPrincipal}" alt="${prod.nombre}">
                <div class="info">
                    <h3>${prod.nombre}</h3>
                    <p class="desc">${prod.descripcion}</p>
                    <div class="precio-tarjeta">
                        <span class="precio">$${prod.precio.toLocaleString('es-AR')}</span>
                        <span class="aclaracion-precio-tarjeta">(Contado)</span>
                    </div>
                    <div class="acciones-tarjeta">
                        <button class="btn-ver" onclick="abrirModalDetalle(${prod.id})">VER</button>
                        <button class="btn-agregar" onclick="agregarAlCarrito(${prod.id})">Agregar al Carrito</button>
                    </div>
                </div>
            </div>
        `;
    });
}

// FUNCIONALIDAD DEL MODAL
function abrirModalDetalle(id) {
    productoModalActual = productos.find(p => p.id === id);
    if (!productoModalActual) return;

    indiceImagenModal = 0;
    actualizarImagenModal();

    document.getElementById('modal-titulo').innerText = productoModalActual.nombre;
    document.getElementById('modal-precio').innerText = `$${productoModalActual.precio.toLocaleString('es-AR')}`;
    document.getElementById('modal-descripcion').innerText = productoModalActual.descripcion;
    document.getElementById('modal-cantidad-input').value = 1;

    // Colores
    const contenedorColores = document.getElementById('modal-lista-colores');
    contenedorColores.innerHTML = '';

    if (productoModalActual.colores && productoModalActual.colores.length > 0) {
        document.getElementById('modal-contenedor-colores').style.display = 'block';
        colorSeleccionadoActual = productoModalActual.colores[0];

        productoModalActual.colores.forEach((col, index) => {
            const btnColor = document.createElement('button');
            btnColor.className = `btn-color-opcion ${index === 0 ? 'seleccionado' : ''}`;
            btnColor.innerText = col;
            btnColor.onclick = () => seleccionarColor(btnColor, col);
            contenedorColores.appendChild(btnColor);
        });
    } else {
        document.getElementById('modal-contenedor-colores').style.display = 'none';
        colorSeleccionadoActual = null;
    }

    // Configurar Botón Añadir en Modal
    const btnAgregarModal = document.getElementById('modal-btn-agregar');
    btnAgregarModal.onclick = () => {
        const cant = parseInt(document.getElementById('modal-cantidad-input').value) || 1;
        agregarAlCarrito(productoModalActual.id, colorSeleccionadoActual, cant);
        cerrarModalDetalleDirecto();
    };

    document.getElementById('modal-producto-overlay').classList.add('activo');
}

// Navegación de Imágenes en Modal
function actualizarImagenModal() {
    const imgs = productoModalActual.imagenes || [productoModalActual.imagen];
    document.getElementById('modal-img-principal').src = imgs[indiceImagenModal];

    const btnIzq = document.querySelector('.flecha-izq');
    const btnDer = document.querySelector('.flecha-der');

    if (imgs.length <= 1) {
        btnIzq.style.display = 'none';
        btnDer.style.display = 'none';
    } else {
        btnIzq.style.display = 'flex';
        btnDer.style.display = 'flex';
    }
}

function cambiarImagenModal(direccion) {
    const imgs = productoModalActual.imagenes || [productoModalActual.imagen];
    indiceImagenModal += direccion;

    if (indiceImagenModal < 0) {
        indiceImagenModal = imgs.length - 1;
    } else if (indiceImagenModal >= imgs.length) {
        indiceImagenModal = 0;
    }

    actualizarImagenModal();
}

// Control de Cantidad dentro del Modal
function cambiarCantidadModal(cambio) {
    const input = document.getElementById('modal-cantidad-input');
    let val = parseInt(input.value) || 1;
    val += cambio;
    if (val < 1) val = 1;
    input.value = val;
}

function seleccionarColor(elementoBtn, color) {
    document.querySelectorAll('.btn-color-opcion').forEach(btn => btn.classList.remove('seleccionado'));
    elementoBtn.classList.add('seleccionado');
    colorSeleccionadoActual = color;
}

function cerrarModalDetalle(e) {
    if (e.target.id === 'modal-producto-overlay') {
        document.getElementById('modal-producto-overlay').classList.remove('activo');
    }
}

function cerrarModalDetalleDirecto() {
    document.getElementById('modal-producto-overlay').classList.remove('activo');
}

// Filtro por Búsqueda
function filtrarPorTexto() {
    const textoBuscado = document.getElementById('input-buscar').value.toLowerCase();
    document.querySelectorAll('.btn-cat, .dropdown-contenido .btn-cat').forEach(btn => btn.classList.remove('activo'));

    const filtrados = productos.filter(prod => {
        const enNombre = prod.nombre.toLowerCase().includes(textoBuscado);
        const enDesc = prod.descripcion.toLowerCase().includes(textoBuscado);
        return enNombre || enDesc;
    });

    mostrarProductosEnPantalla(filtrados);
}

